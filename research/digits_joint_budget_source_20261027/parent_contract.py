"""Strict fresh-matched parent custody contract. Standard library, no array loads.

This is NOT a validator of the historical PARENT.json chain. Descriptors are
private custody inputs, never automatic authorization or public-safe payloads.
"""
from __future__ import annotations
import datetime
import hashlib
import json
import math
import pathlib
import re

CONTRACT = 'canaria.grid-parent.v1'
MATCHED_CONTRACT = 'canaria.matched-replication.v1'
CLOSED = 'CLOSED_NOT_REOPENED'
SEED_FILES = (
    'START.json', 'environment.json', 'split_ids.npz', 'data_hashes.json',
    'teacher_initial.npz', 'teacher_final.npz', 'fit_targets.npz',
    'pair_initial.npz', 'comp_initial.npz', 'schedule.npy',
    'L_final.npz', 'J_final.npz', 'C_final.npz',
    'L_updates.jsonl', 'J_updates.jsonl', 'C_updates.jsonl',
    'validation_arrays.npz', 'result.json', 'FILES_SHA256.json',
)
ARTIFACT_PATHS = frozenset(
    ['run_contract.json', 'SUMMARY.json', 'FILES_SHA256.json']
    + [f'seed_{i}{suffix}' for i in range(16) for suffix in ('.log', '_EXIT.json')]
    + [f'seed_{i}/{name}' for i in range(16) for name in SEED_FILES]
)
CUSTODY_PATHS = frozenset(
    ['claim.json', 'cohort.json', 'FINISHED.json']
    + [f'seed_{i}.started.json' for i in range(16)]
)
DIGEST = re.compile(r'[0-9a-f]{64}')


def sha(path):
    return hashlib.sha256(pathlib.Path(path).read_bytes()).hexdigest()


def read_json(path):
    return json.loads(pathlib.Path(path).read_text())


def identity(value):
    if not isinstance(value, str) or re.fullmatch(r'replication-[a-z0-9][a-z0-9-]{0,63}', value) is None:
        raise ValueError('new matched replication identity required')
    return value


def timestamp(value):
    if not isinstance(value, str):
        raise ValueError('UTC time required')
    parsed = datetime.datetime.fromisoformat(value.replace('Z', '+00:00'))
    if parsed.tzinfo is None or parsed.utcoffset() != datetime.timedelta(0):
        raise ValueError('UTC time required')
    return parsed.timestamp()


def digest_map(value, expected):
    if not isinstance(value, dict) or set(value) != set(expected):
        raise ValueError('exact manifest path census required')
    if any(not isinstance(v, str) or DIGEST.fullmatch(v) is None for v in value.values()):
        raise ValueError('invalid SHA256 value')
    return value


def contained(root, rel):
    path = pathlib.Path(rel)
    if path.is_absolute() or '..' in path.parts or str(path) != rel or '\\' in rel:
        raise ValueError('unsafe relative path')
    root = pathlib.Path(root)
    for part in (root, *root.parents):
        if part.is_symlink():
            raise ValueError('symlink in parent root')
    target = root / path
    for part in (target, *target.parents):
        if part == root:
            break
        if part.is_symlink():
            raise ValueError('symlink in parent artifact/custody path')
    if not target.resolve().is_relative_to(root.resolve()):
        raise ValueError('parent path escape')
    return target


def complete_files(root, expected):
    root = pathlib.Path(root)
    if not root.is_dir() or root.is_symlink():
        raise ValueError('existing nonsymlink parent directory required')
    observed = set()
    for path in root.rglob('*'):
        if path.is_symlink():
            raise ValueError('symlink in parent tree')
        if path.is_file():
            observed.add(path.relative_to(root).as_posix())
        elif not path.is_dir():
            raise ValueError('nonregular parent entry')
    if observed != set(expected):
        raise ValueError('parent full-file census mismatch')
    return {rel: sha(contained(root, rel)) for rel in sorted(expected)}


def dependency(package_root):
    """Verify every byte of the already-public matched dependency before import."""
    package_root = pathlib.Path(package_root)
    spec = read_json(package_root / 'DEPENDENCY.json')
    if spec['schema'] != 'canaria.grid-matched-dependency.v1' or spec['contract'] != MATCHED_CONTRACT:
        raise ValueError('dependency contract mismatch')
    if spec['sibling_directory'] != 'digits_matched_source_20261027':
        raise ValueError('unexpected dependency layout')
    root = package_root.parent / spec['sibling_directory']
    # No requirement to exclude caches generated by separately approved tests.
    for rel, digest in spec['files'].items():
        if DIGEST.fullmatch(digest) is None or sha(contained(root, rel)) != digest:
            raise ValueError('matched source dependency changed: ' + rel)
    required = spec['matched_required_files']
    if any(spec['files'].get(k) != v for k, v in required.items()):
        raise ValueError('matched required-file closure mismatch')
    package_id = hashlib.sha256(json.dumps(required, sort_keys=True, separators=(',', ':')).encode()).hexdigest()
    if package_id != spec['matched_package_sha256']:
        raise ValueError('matched package identity mismatch')
    return root, spec


def parent_paths(workspace, replication_id):
    identity(replication_id)
    workspace = pathlib.Path(workspace)
    if not workspace.is_dir() or workspace.is_symlink():
        raise ValueError('existing parent custody workspace required')
    artifacts = contained(workspace, 'artifacts/' + replication_id)
    custody = contained(workspace, 'custody/matched/' + replication_id)
    return artifacts, custody


def validate_reused_parent_row(row, seed):
    """Check scalar reuse identity; array/state identities stay checked by runner."""
    if row.get('id') != seed['id'] or row.get('seed') != seed or row.get('status') != 'COMPLETE':
        raise ValueError('parent seed/result identity mismatch')
    tc = row.get('teacher_correct')
    if type(tc) is not int or not 0 <= tc <= 270:
        raise ValueError('invalid parent teacher count')
    for key in ('teacher_initial_sha256', 'teacher_final_sha256', 'schedule_sha256'):
        if not isinstance(row.get(key), str) or DIGEST.fullmatch(row[key]) is None:
            raise ValueError('parent tensor identity missing')
    if set(row.get('arms', {})) != {'L', 'J', 'C'} or set(row.get('fit_records', {})) != {'L', 'J', 'C'}:
        raise ValueError('parent arm census mismatch')
    for arm in ('L', 'J', 'C'):
        cell = row['arms'][arm]
        nmse = cell.get('nmse')
        correct = cell.get('correct')
        if type(nmse) not in (float, int) or not math.isfinite(nmse) or nmse < 0:
            raise ValueError('invalid parent NMSE')
        if cell.get('n') != 270 or type(correct) is not int or not 0 <= correct <= 270:
            raise ValueError('invalid parent count')
        if cell.get('accuracy') != correct / 270 or type(cell.get('quality_pass')) is not bool:
            raise ValueError('invalid parent accuracy/pass type')
        if cell['quality_pass'] != (nmse <= .08 and correct / 270 >= tc / 270 - .02):
            raise ValueError('parent 2048 pass mismatch')
        if not isinstance(cell.get('state_sha256'), str) or DIGEST.fullmatch(cell['state_sha256']) is None:
            raise ValueError('parent arm state identity missing')
        fit = row['fit_records'][arm]
        if fit.get('schedule_sha256') != row['schedule_sha256'] or fit.get('parameter_steps') != [600] * (2 if arm == 'C' else 4) or fit.get('examples_per_parameter') != 76800:
            raise ValueError('parent final-step/shared-schedule contract mismatch')
    return row


def validate_completed_parent(workspace, replication_id, package_root):
    """Full bytes + nested manifests + successful output/custody cross-bindings."""
    matched_root, dep = dependency(package_root)
    root, custody = parent_paths(workspace, replication_id)
    files = complete_files(root, ARTIFACT_PATHS)
    custody_files = complete_files(custody, CUSTODY_PATHS)
    expected_top = {k: v for k, v in files.items() if k != 'FILES_SHA256.json'}
    if read_json(root / 'FILES_SHA256.json') != expected_top:
        raise ValueError('parent complete root manifest mismatch')
    for i in range(16):
        expected_seed = {name: files[f'seed_{i}/{name}'] for name in SEED_FILES if name != 'FILES_SHA256.json'}
        if read_json(root / f'seed_{i}/FILES_SHA256.json') != expected_seed:
            raise ValueError('parent nested manifest mismatch')
    summary = read_json(root / 'SUMMARY.json')
    if summary.get('decision') not in ('CONDITIONAL_REGIME_SUPPORTED', 'NOT_JOINTLY_SUPPORTED'):
        raise ValueError('parent is not a complete matched cohort')
    if summary.get('abort_reason') is not None or summary.get('not_started') != []:
        raise ValueError('parent aborted or not-started member')
    attempts = summary.get('attempts', [])
    if len(attempts) != 16 or {r.get('id') for r in attempts} != set(range(16)) or any(type(r.get('returncode')) is not int or r['returncode'] != 0 or r.get('reason') is not None for r in attempts):
        raise ValueError('parent successful-exit census mismatch')
    seeds = read_json(matched_root / 'SEEDS.json')['seeds']
    rows = summary.get('all_rows', [])
    if len(rows) != 16 or {r.get('id') for r in rows} != set(range(16)):
        raise ValueError('parent summary row census mismatch')
    for seed in seeds:
        i = seed['id']
        row = read_json(root / f'seed_{i}/result.json')
        validate_reused_parent_row(row, seed)
        if next(r for r in rows if r['id'] == i) != row:
            raise ValueError('parent summary/result mismatch')
        if read_json(root / f'seed_{i}_EXIT.json') != next(r for r in attempts if r['id'] == i):
            raise ValueError('parent summary/exit mismatch')
        if read_json(custody / f'seed_{i}.started.json').get('id') != i:
            raise ValueError('parent admission identity mismatch')
    run = read_json(root / 'run_contract.json')
    run_keys = {'contract', 'replication_id', 'evidence_class', 'historical_attempt', 'package_sha256', 'files', 'deadline_utc'}
    if set(run) != run_keys or run['contract'] != MATCHED_CONTRACT or run['replication_id'] != replication_id or run['evidence_class'] != 'new-replication-on-seen-digits' or run['historical_attempt'] != CLOSED:
        raise ValueError('not a fresh matched parent contract')
    if run['package_sha256'] != dep['matched_package_sha256'] or run['files'] != dep['matched_required_files']:
        raise ValueError('parent matched source identity mismatch')
    cohort = read_json(custody / 'cohort.json')
    release = cohort.get('release', {})
    private_keys = {'custody_attestation', 'parent_approved', 'independent_review', 'reviewer', 'approval_evidence'}
    if set(release) != run_keys | private_keys or {k: release[k] for k in run_keys} != run:
        raise ValueError('parent private/public release mismatch')
    if release['parent_approved'] is not True or release['independent_review'] != 'GO' or release['custody_attestation'] != 'SINGLE_DURABLE_ROOT_NO_PRIOR_ATTEMPT_NO_RETRY':
        raise ValueError('parent private approval/custody contract missing')
    if any(not isinstance(release[k], str) or not release[k].strip() for k in ('reviewer', 'approval_evidence')):
        raise ValueError('parent private approval provenance missing')
    if cohort.get('status') != 'STARTED' or pathlib.Path(cohort.get('out', '')).resolve() != root.resolve() or not isinstance(cohort.get('token_hash'), str) or DIGEST.fullmatch(cohort['token_hash']) is None:
        raise ValueError('parent cohort custody binding mismatch')
    claim = read_json(custody / 'claim.json')
    if claim.get('replication_id') != replication_id or claim.get('package_sha256') != dep['matched_package_sha256'] or claim.get('output_relative') != 'artifacts/' + replication_id:
        raise ValueError('parent permanent claim mismatch')
    finished = read_json(custody / 'FINISHED.json')
    if finished.get('summary_sha256') != files['SUMMARY.json'] or finished.get('decision') != summary['decision']:
        raise ValueError('parent completion custody mismatch')
    # An expired *completed* parent is valid; no deadline is extended or revived.
    start, end = timestamp(cohort['utc']), timestamp(summary['finished_utc'])
    if not start <= end <= cohort['end_timestamp'] <= timestamp(run['deadline_utc']):
        raise ValueError('parent completion deadline binding mismatch')
    if timestamp(finished['utc']) < end:
        raise ValueError('parent completion timestamp mismatch')
    return {
        'contract': CONTRACT, 'parent_contract': MATCHED_CONTRACT,
        'historical_attempt': CLOSED, 'parent_replication_id': replication_id,
        'matched_package_sha256': dep['matched_package_sha256'],
        'files': files, 'custody_files': custody_files,
    }


def verify_parent(workspace, manifest, package_root):
    keys = {'contract', 'parent_contract', 'historical_attempt', 'parent_replication_id', 'matched_package_sha256', 'files', 'custody_files'}
    if not isinstance(manifest, dict) or set(manifest) != keys:
        raise ValueError('parent descriptor fields missing or unknown')
    if manifest['contract'] != CONTRACT or manifest['parent_contract'] != MATCHED_CONTRACT or manifest['historical_attempt'] != CLOSED:
        raise ValueError('historical parent cannot be relabelled as fresh')
    digest_map(manifest['files'], ARTIFACT_PATHS)
    digest_map(manifest['custody_files'], CUSTODY_PATHS)
    actual = validate_completed_parent(workspace, manifest['parent_replication_id'], package_root)
    if actual != manifest:
        raise ValueError('parent artifact/custody descriptor changed')
    return parent_paths(workspace, manifest['parent_replication_id'])[0]


def main():
    import argparse
    parser = argparse.ArgumentParser(description='Build a PRIVATE descriptor of an already completed, separately approved matched replication; does not run models.')
    parser.add_argument('--workspace', type=pathlib.Path, required=True)
    parser.add_argument('--replication-id', required=True)
    parser.add_argument('--out', type=pathlib.Path, required=True)
    args = parser.parse_args()
    package_root = pathlib.Path(__file__).resolve().parent
    root, custody = parent_paths(args.workspace, args.replication_id)
    output = args.out.resolve()
    if any(output.is_relative_to(p.resolve()) for p in (root, custody, package_root, package_root.parent / 'digits_matched_source_20261027')):
        parser.error('descriptor must be outside source, parent artifacts and parent custody')
    manifest = validate_completed_parent(args.workspace, args.replication_id, package_root)
    with args.out.open('x') as stream:
        json.dump(manifest, stream, indent=2, sort_keys=True, allow_nan=False)
        stream.write('\n')


if __name__ == '__main__':
    main()
